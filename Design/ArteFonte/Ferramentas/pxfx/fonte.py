def _build(table, h):
    out = {}
    for ch, src in table.items():
        rows = src.split("|")
        if len(rows) != h:
            raise ValueError(f"glifo {ch} tem {len(rows)} linhas, esperado {h}")
        out[ch] = {"w": len(rows[0]), "rows": [[c == "#" for c in r] for r in rows]}
    return out


FONTS = {
    "mini": {"h": 5, "space": 2, "gap": 1, "glyphs": _build(MINI, 5)},
    "big": {"h": 7, "space": 3, "gap": 1, "glyphs": _build(BIG, 7)},
}


def _glyph(F, ch):
    return F["glyphs"].get(ch) or F["glyphs"].get(ch.upper())


def textWidth(s, font="mini"):
    """Largura em pixels de fonte de uma string (antes da escala)."""
    F = FONTS[font]
    w = 0
    for ch in str(s):
        g = _glyph(F, ch)
        w += (g["w"] if g else F["space"]) + F["gap"]
    return max(0, w - F["gap"])


def rasterText(s, font, plot):
    """Chama plot(x, y) para cada pixel com tinta, com o canto do texto em (0, 0)."""
    F = FONTS[font]
    x = 0
    for ch in str(s):
        g = _glyph(F, ch)
        if not g:
            x += F["space"] + F["gap"]
            continue
        for r in range(F["h"]):
            for c in range(g["w"]):
                if g["rows"][r][c]:
                    plot(x + c, r)
        x += g["w"] + F["gap"]
